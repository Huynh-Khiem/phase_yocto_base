struct fb_ctx {
	int fd;
	char dev_path[32];
	uint8_t *mem;
	size_t mem_size;
	uint8_t *frame;
	size_t frame_size;
	struct fb_var_screeninfo vinfo;
	struct fb_fix_screeninfo finfo;
};

/* Tu dong tim /dev/fbX thuoc driver st7735r (tranh nham voi HDMI fb0) */
static int find_st7735r_fb(char *out_path, size_t out_len)
{
	char sys_path[64];
	char name[64];

	for (int i = 0; i < 8; i++) {
		snprintf(sys_path, sizeof(sys_path),
			 "/sys/class/graphics/fb%d/name", i);
		FILE *f = fopen(sys_path, "r");
		if (!f)
			continue;
		if (fgets(name, sizeof(name), f)) {
			if (strstr(name, "st7735r") != NULL) {
				fclose(f);
				snprintf(out_path, out_len, "/dev/fb%d", i);
				return 0;
			}
		}
		fclose(f);
	}
	return -1;
}

static void fb_close(struct fb_ctx *ctx)
{
	free(ctx->frame);
	ctx->frame = NULL;
	if (ctx->mem && ctx->mem != MAP_FAILED) {
		munmap(ctx->mem, ctx->mem_size);
		ctx->mem = NULL;
	}
	if (ctx->fd >= 0) {
		close(ctx->fd);
		ctx->fd = -1;
	}
}

static int fb_open_st7735r(struct fb_ctx *ctx)
{
	memset(ctx, 0, sizeof(*ctx));
	ctx->fd = -1;

	if (find_st7735r_fb(ctx->dev_path, sizeof(ctx->dev_path)) < 0)
		return -1;

	ctx->fd = open(ctx->dev_path, O_RDWR);
	if (ctx->fd < 0)
		return -1;

	if (ioctl(ctx->fd, FBIOGET_FSCREENINFO, &ctx->finfo) < 0 ||
	    ioctl(ctx->fd, FBIOGET_VSCREENINFO, &ctx->vinfo) < 0) {
		fb_close(ctx);
		return -1;
	}

	ctx->mem_size = ctx->finfo.smem_len;
	ctx->mem = mmap(NULL, ctx->mem_size, PROT_READ | PROT_WRITE,
			MAP_SHARED, ctx->fd, 0);
	if (ctx->mem == MAP_FAILED) {
		ctx->mem = NULL;
		fb_close(ctx);
		return -1;
	}

	/* Dam bao man hinh dang bat (unblank) */
	(void)ioctl(ctx->fd, FBIOBLANK, FB_BLANK_UNBLANK);

	printf("[TFT] Da ket noi %s (%ux%u, %u bpp)\n",
	       ctx->dev_path, ctx->vinfo.xres, ctx->vinfo.yres,
	       ctx->vinfo.bits_per_pixel);
	fflush(stdout);
	return 0;
}

static void draw_char(const struct fb_ctx *ctx, uint8_t *frame, int x, int y,
		      char c, int scale)
{
	if (c < 0x20 || c > 0x7E)
		c = '?';

	const uint8_t *glyph = font8x8_basic[c - 0x20];
	size_t pixel_size = ctx->vinfo.bits_per_pixel / 8;
	for (int dy = 0; dy < 8 * scale && (uint32_t)(y + dy) < ctx->vinfo.yres; dy++) {
		uint8_t *row = frame + (size_t)(y + dy) * ctx->finfo.line_length;
		uint8_t bits = glyph[dy / scale];
		for (int dx = 0; dx < 8 * scale && (uint32_t)(x + dx) < ctx->vinfo.xres; dx++) {
			if (bits & (1 << (dx / scale)))
				memset(row + (size_t)(x + dx) * pixel_size, 0xff, pixel_size);
		}
	}
}

static void draw_text(const struct fb_ctx *ctx, uint8_t *frame, int x, int y,
		      const char *str, int scale)
{
	while (*str && (uint32_t)x < ctx->vinfo.xres) {
		draw_char(ctx, frame, x, y, *str, scale);
		x += 8 * scale;
		str++;
	}
}

static int prepare_frame(struct fb_ctx *ctx)
{
	size_t stride = ctx->finfo.line_length;
	uint32_t bpp = ctx->vinfo.bits_per_pixel;
	if ((bpp != 16 && bpp != 32) || !stride || !ctx->vinfo.yres ||
	    ctx->vinfo.xres > stride / (bpp / 8) ||
	    ctx->vinfo.yres > ctx->mem_size / stride) {
		fprintf(stderr, "[TFT] Dinh dang framebuffer khong duoc ho tro.\n");
		return -1;
	}

	/* Ve xong chu trang tren nen den truoc khi ghi vao framebuffer. */
	ctx->frame_size = stride * ctx->vinfo.yres;
	uint8_t *frame = calloc(1, ctx->frame_size);
	if (!frame) {
		perror("[TFT] Khong the cap phat bo dem");
		return -1;
	}

	draw_text(ctx, frame, 8, 9, "PI 4B - ST7735R", 1);
	draw_text(ctx, frame, 8, 40, "HELLO", 2);
	draw_text(ctx, frame, 8, 64, "YOCTO!", 2);
	draw_text(ctx, frame, 8, 98, "Status: OK", 1);
	ctx->frame = frame;
	return 0;
}

static int fb_is_connected(const struct fb_ctx *ctx)
{
	struct fb_var_screeninfo vinfo;

	return access(ctx->dev_path, F_OK) == 0 &&
	       ioctl(ctx->fd, FBIOGET_VSCREENINFO, &vinfo) == 0;
}

int main(void)
{
	struct fb_ctx ctx = { .fd = -1 };

	signal(SIGINT, handle_sig);
	signal(SIGTERM, handle_sig);

	printf("Khoi dong tft-test (cap nhat moi %d giay; Ctrl+C de thoat)\n",
	       REFRESH_INTERVAL_SEC);

	while (g_running) {
		if (ctx.fd < 0) {
			if (fb_open_st7735r(&ctx) < 0) {
				printf("[TFT] Chua thay man hinh ST7735R. Thu ket noi lai sau %d giay...\n",
				       RECONNECT_RETRY_SEC);
				fflush(stdout);
				sleep(RECONNECT_RETRY_SEC);
				continue;
			}
			if (prepare_frame(&ctx) < 0) {
				fb_close(&ctx);
				return EXIT_FAILURE;
			}
		}

		if (!fb_is_connected(&ctx)) {
			printf("[TFT] Mat ket noi %s! Dang khoi phuc...\n", ctx.dev_path);
			fflush(stdout);
			fb_close(&ctx);
			sleep(RECONNECT_RETRY_SEC);
			continue;
		}

		/* Ghi lai ca khung, ke ca khi noi dung chu khong doi. */
		memcpy(ctx.mem, ctx.frame, ctx.frame_size);
		sleep(REFRESH_INTERVAL_SEC);
	}

	fb_close(&ctx);
	printf("\nDa dung tft-test.\n");
	return EXIT_SUCCESS;
}
